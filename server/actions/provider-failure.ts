// Only these bounded categories may cross the authenticated worker boundary.
// Provider bodies, prompts, stack traces and transport exceptions stay private.
const safeCodes=new Set([
 'PROVIDER_RATE_LIMIT','PROVIDER_REFUSED','OWNER_APPROVAL_REQUIRED','SPENDING_CUTOFF','INPUT_TOKEN_LIMIT',
 'GAME_FORM_UNSUPPORTED','GAME_FORM_REVIEW_REQUIRED','GAME_FORM_BASE_UNVERIFIED','IMAGE_APPROVAL_REQUIRED',
 'IMAGE_ALLOWANCE_EXCEEDED','IMAGE_PROVIDER_RATE_LIMIT','IMAGE_PROVIDER_FAILED','QUALITY_REVIEW_REQUIRED',
 'QUALITY_EVIDENCE_CAPACITY_EXCEEDED','PREMIUM_V2_REQUIRED',
 'MODEL_POLICY_UNAVAILABLE','MODEL_ACCESS_UNAVAILABLE','MODEL_POLICY_MISMATCH','PROVIDER_INCOMPLETE',
 'PROVIDER_USAGE_INVALID','PREMIUM_APPROVAL_REQUIRED','PREMIUM_PRICING_OR_LIMIT_INVALID','PREMIUM_PROVIDER_APPROVAL_REQUIRED',
 'PREMIUM_MODEL_POLICY_INVALID','REQUEST_TIMEOUT_REQUIRED','PROVIDER_KEY_MISSING','PROVIDER_TIMEOUT','CANCELLED'
]);
export function safeProviderFailure(code:unknown):string{
 return typeof code==='string'&&safeCodes.has(code)?code:'PROVIDER_FAILED';
}
