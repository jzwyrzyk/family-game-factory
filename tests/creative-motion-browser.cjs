/** Synthetic artwork only. Exercise the real shelf, movement versions and scene engine. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {once}=require('node:events');
const {mkdirSync,readFileSync}=require('node:fs');
const {start}=require('./browser-server.cjs');

(async()=>{
  const server=start(process.env.JEMS_TEST_DIST || 'dist');
  if(!server.listening)await once(server,'listening');
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']});
  try {
    const page=await browser.newPage({viewport:{width:1200,height:850}});
    const posts=[], errors=[];
    page.on('request',request=>{if(request.method()==='POST')posts.push(request.url());});
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/factory-config.json',route=>route.fulfill({contentType:'application/json',body:'{"version":1,"mode":"unavailable"}'}));
    await page.goto('http://127.0.0.1:'+server.address().port+'/arcade/?art=1');
    const bytes=await page.evaluate(()=>{
      const c=document.createElement('canvas'); c.width=96;c.height=72;
      const ctx=c.getContext('2d');
      ctx.fillStyle='#775765';ctx.strokeStyle='#2f2541';ctx.lineWidth=3;
      ctx.beginPath();ctx.moveTo(8,56);ctx.lineTo(15,32);ctx.lineTo(31,15);ctx.lineTo(58,10);ctx.lineTo(83,29);ctx.lineTo(91,53);ctx.lineTo(68,65);ctx.lineTo(27,63);ctx.closePath();ctx.fill();ctx.stroke();
      ctx.fillStyle='white';ctx.fillRect(36,30,8,10);ctx.fillRect(61,29,9,10);
      ctx.fillStyle='#34283e';ctx.fillRect(40,35,3,4);ctx.fillRect(65,33,3,5);
      ctx.beginPath();ctx.moveTo(43,45);ctx.lineTo(52,50);ctx.lineTo(61,44);ctx.stroke();
      return c.toDataURL().split(',')[1];
    });
    await page.setInputFiles('#artUpload',{name:'Skipping stone.png',mimeType:'image/png',buffer:Buffer.from(bytes,'base64')});
    await page.locator('#artDrawPath').click();
    const editor=page.locator('dialog.motion-path'), canvas=editor.locator('canvas'), bounds=await canvas.boundingBox();
    const tap=async(x,y)=>canvas.click({position:{x:bounds.width*x,y:bounds.height*y}});
    await tap(.2,.7); assert.equal(await editor.locator('[data-save]').isEnabled(),false);
    await tap(.5,.25);await tap(.8,.65);
    await canvas.press('ArrowUp');await canvas.press('Enter');
    await editor.locator('[data-undo]').click();
    assert.match(await editor.locator('[data-status]').textContent(),/3 stops/);
    await editor.locator('[data-speed]').selectOption('300');
    await editor.locator('[data-preview]').click();await editor.getByRole('button',{name:'Stop',exact:true}).click();
    mkdirSync('test-results/creative-motion',{recursive:true});
    await editor.screenshot({path:'test-results/creative-motion/animation-path.png'});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await editor.evaluate(d=>d.scrollWidth<=d.clientWidth),true);
    await editor.screenshot({path:'test-results/creative-motion/animation-path-phone.png'});
    await page.setViewportSize({width:1200,height:850});
    await editor.locator('[data-save]').click();await editor.waitFor({state:'detached'});
    const first=await page.locator('#artVersion').inputValue();
    assert.ok(first);
    const original=await page.locator('.art-card[aria-pressed="true"]').getAttribute('data-art-id');
    await page.evaluate(()=>{FG.store.changeProfile({rate:1});FG.store.current().mathWindow=[Date.now()];FG.store.save();});
    await page.locator('#artUseScene').click();
    await page.locator('#creationWorkspace').waitFor({state:'visible'});
    const scene=await page.evaluate(()=>FG.creation.scene());
    const actor=scene.actors[0], actions=scene.programs[0].actions;
    assert.equal(scene.provenance.sourceRevisionId,first);
    assert.ok(actor.assetId.startsWith('art:rig:'+first+':'));
    assert.equal(actions.length,2);
    assert.ok(actions.every(a=>a.type==='move'&&a.origin==='child'&&a.durationMs===300));
    await page.locator('#creationRun').click();
    await page.waitForFunction(()=>FG.creation.snapshot()?.status==='completed');
    const final=await page.evaluate(()=>FG.creation.snapshot().actors[0]);
    assert.equal(final.x,actions[1].x);assert.equal(final.y,actions[1].y);
    await page.locator('#creationCanvas').screenshot({path:'test-results/creative-motion/path-playback.png'});
    await page.locator('#creationMore summary').click();
    const downloading=page.waitForEvent('download');await page.locator('#creationDownload').click();
    const bundle=JSON.parse(readFileSync(await (await downloading).path(),'utf8'));
    assert.equal(bundle.art.drawings[0].data,bytes,'exported artwork preserves exact PNG bytes');
    assert.equal(bundle.art.rigs[0].assembly.motion.points.length,3);
    assert.equal(bundle.art.rigs[0].assembly.motion.sprite,'original');
    assert.ok(bundle.art.rigs[0].assembly.pieces.every(piece=>!piece.physical),'drawing a path assigns no physical behavior');
    assert.equal(bundle.art.rigs[0].id,first);
    await page.evaluate(id=>FG.artStudio.open(id),original);
    await page.locator('#artDrawPath').click();await editor.locator('[data-speed]').selectOption('1000');
    await editor.locator('[data-save]').click();await editor.waitFor({state:'detached'});
    const second=await page.locator('#artVersion').inputValue();
    assert.notEqual(first,second);
    await page.locator('#artVersion').selectOption(first);await page.locator('#artUseScene').click();
    await page.waitForFunction(()=>FG.creation.scene()?.programs[0]?.actions[0]?.durationMs===300);
    const reused=await page.evaluate(()=>FG.creation.scene());assert.equal(reused.actors[0].assetId,actor.assetId);
    assert.deepEqual(reused.programs[0].actions.map(({id,...action})=>action),actions.map(({id,...action})=>action));
    const stored=await page.evaluate(()=>FG.creation.export());
    assert.ok(stored.revisions.some(r=>JSON.stringify(r.scene)===JSON.stringify(scene)),'the first scene survives a new motion revision unchanged');
    assert.equal(stored.attempts.length,0);
    await page.locator('#creationAddActor').click();
    const movementChoices=page.locator('#creationPrivateActorChoices [data-private-art]').filter({hasText:'Animation path'});
    const collection=page.locator('#creationActorArtFilters').getByLabel('Art collection');
    assert.equal((await movementChoices.first().getAttribute('data-private-art')).split(':')[2],second,'The newest saved version comes first in All my art');
    await collection.selectOption('recent');
    assert.equal(await movementChoices.first().getAttribute('data-private-art'),actor.assetId,'Recent shows the first version just reused in a scene');
    await collection.selectOption('');
    assert.equal(await movementChoices.last().getAttribute('data-private-art'),actor.assetId,'All my art keeps the saved order of the two versions');
    await movementChoices.last().click();
    const added=await page.evaluate(()=>FG.creation.scene());assert.equal(added.actors[1].assetId,actor.assetId);
    const inserted=added.programs.find(p=>p.actorId===added.actors[1].id && p.trigger.type==='start');
    assert.deepEqual(inserted.actions.map(({id,...a})=>a),actions.map(({id,...a})=>a));
    assert.deepEqual(posts,[]);assert.deepEqual(errors,[]);
    console.log('Draw to animation passed: pointer and keyboard path, preview, three saved stops, playback, exact old version, phone layout, zero POSTs.');
  } finally {await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
